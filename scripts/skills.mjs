// The Skills scripts/build.mjs generates from the packs, so no file of a
// pack is kept twice by hand:
//
//   skills/emile-shaders/     the Skill other people's agents install: it
//                             is copied on its own, so it carries every
//                             pack's pack.json, shader.glsl and SKILL.md as
//                             they are, the runner, the example page and
//                             the references (templates in
//                             scripts/skills/emile-shaders/)
//   skills/choosing-filters/  an official reference Skill for Émile: the
//                             filters' guides drawn into one page to
//                             choose from (scripts/skills/choosing-filters/)
//
// A template's {{generated}} becomes the note that the file is generated;
// a .js or .html file gets it as its first comment. The packs' own files
// go in byte for byte, so they carry no note: the folder's SKILL.md says
// where everything comes from.

import fs from 'node:fs'
import path from 'node:path'

export const GENERATED = ['emile-shaders', 'choosing-filters']

const ORDER = ['print', 'texture', 'distort', 'color', 'glow', 'film']
const GROUP = { print: 'Print', texture: 'Texture', distort: 'Distort', color: 'Color', glow: 'Glow', film: 'Film' }

const note = from => `Generated by scripts/build.mjs in github.com/EmileFilm/emile-packs from ${from}: do not edit it here, edit those and run the build.`

// A guide's section by its heading, as it is written
const section = (guide, title) => new RegExp(`^## ${title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, 'm').exec(guide)?.[1].trim() ?? ''
const bullets = text => text.split('\n').filter(l => l.startsWith('- ')).map(l => l.slice(2).trim())
// A bullet's first sentence (decimals like 0.5 are no full stop)
const firstSentence = s => (/^([\s\S]*?\.)(\s|$)/.exec(s)?.[1] ?? s).trim()
// A moment's name: its bold words, else what comes before the first colon
const momentOf = s => (/\*\*(.+?)\*\*/.exec(s)?.[1] ?? s.split(/:\s/)[0]).trim()
const cell = s => s.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|')
// The words a guide says call for it
const wordsOf = guide => bullets(section(guide, 'When to use')).find(b => /^Words that call for it/i.test(b))?.replace(/^Words that call for it:\s*/i, '').replace(/\.$/, '') ?? ''
// A transition's length, from the line under its heading (0.3–0.8 s)
const lengthOf = guide => /(\d[\d.]*–\d[\d.]* s)\b/.exec(guide.replace(/^---[\s\S]*?---/, '').split('\n## ')[0])?.[1] ?? ''

function readPacks(packDirs) {
  return packDirs.map(dir => {
    const pack = JSON.parse(fs.readFileSync(path.join(dir, 'pack.json'), 'utf8'))
    const read = f => fs.readFileSync(path.join(dir, f), 'utf8')
    return { dir, name: path.basename(dir), pack, guide: read('SKILL.md'), glsl: read(pack.backends.glsl), passes: Object.fromEntries((pack.passes ?? []).map(p => [p.id, read(p.glsl)])) }
  })
}

const byGroup = all => all.filter(p => p.pack.kind === 'filter').sort((a, b) => ORDER.indexOf(a.pack.category) - ORDER.indexOf(b.pack.category) || a.name.localeCompare(b.name))

// Every file of the generated Skills: { 'skills/<name>/<path>': Buffer }
export function generateSkills(root, packDirs, contract) {
  const all = readPacks(packDirs)
  const filters = byGroup(all)
  const transitions = all.filter(p => p.pack.kind === 'transition').sort((a, b) => a.name.localeCompare(b.name))
  const out = new Map()
  const put = (rel, text) => out.set(rel, Buffer.isBuffer(text) ? text : Buffer.from(text))
  const template = (skill, rel) => fs.readFileSync(path.join(root, 'scripts', 'skills', skill, rel), 'utf8')
  const fill = (text, values) => text.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in values)) throw new Error(`a template names {{${k}}}, which the build doesn't fill`)
    return values[k]
  })
  const folderOf = p => `${p.pack.kind === 'filter' ? 'filters' : 'transitions'}/${p.name}`

  // ---------------------------------------------------------------- emile-shaders
  const S = 'skills/emile-shaders'
  const from = 'the packs (emile/<name>/) and scripts/skills/emile-shaders/'
  const md = `<!-- ${note(from)} The files under filters/ and transitions/ are the packs' own, byte for byte. -->`

  const filterTable = ['| Group | Filter | What it brings | Folder |', '|---|---|---|---|',
    ...filters.map(p => `| ${GROUP[p.pack.category]} | ${p.pack.title.en} \`${p.pack.id}\` | ${cell(p.pack.description.en)} | \`${folderOf(p)}/\` |`)].join('\n')
  const transitionTable = ['| Transition | What it brings | Length | Folder |', '|---|---|---|---|',
    ...transitions.map(p => `| ${p.pack.title.en} \`${p.pack.id}\` | ${cell(p.pack.description.en)} | ${lengthOf(p.guide)} | \`${folderOf(p)}/\` |`)].join('\n')
  put(`${S}/SKILL.md`, fill(template('emile-shaders', 'SKILL.md'), { generated: md, filters: filterTable, transitions: transitionTable }))

  const grain = all.find(p => p.pack.id === 'emile/grain') ?? filters[0]
  put(`${S}/references/contract.md`, fill(template('emile-shaders', 'references/contract.md'), {
    generated: md,
    filterWrap: contract.fragmentSource('filter', '/* shader.glsl, as it is */', grain.pack.params),
    transitionWrap: contract.fragmentSource('transition', '/* shader.glsl, as it is */', []),
    passWrap: contract.fragmentSource('pass', '/* blur-x.glsl, as it is */', grain.pack.params, ['bright'])
  }))
  put(`${S}/references/wiring.md`, fill(template('emile-shaders', 'references/wiring.md'), { generated: md }))

  // How to choose: each filter's Role, Suits, Doesn't suit and How long
  const choosing = [md, '', '# Choosing a filter or a transition', '',
    'Drawn from each pack\'s `SKILL.md`: its Role, what it suits and doesn\'t (the first sentence of each point) and how long it holds up. Choose here, then read the pack\'s own guide for the settings and the setting that mends a picture it fails on.', '']
  for (const g of ORDER) {
    const group = filters.filter(p => p.pack.category === g)
    if (!group.length) continue
    choosing.push(`## ${GROUP[g]}`, '', '| Filter | Role | Suits | Doesn\'t suit | How long |', '|---|---|---|---|---|')
    for (const p of group) choosing.push(`| \`${p.pack.id}\` | ${cell(section(p.guide, 'Role'))} | ${cell(bullets(section(p.guide, 'Suits')).map(firstSentence).join(' · '))} | ${cell(bullets(section(p.guide, "Doesn't suit")).map(firstSentence).join(' · '))} | ${cell(section(p.guide, 'How long'))} |`)
    choosing.push('')
  }
  choosing.push('## Transitions', '', '| Transition | Length | Suits | Doesn\'t suit |', '|---|---|---|---|')
  for (const p of transitions) choosing.push(`| \`${p.pack.id}\` | ${lengthOf(p.guide)} | ${cell(bullets(section(p.guide, 'Suits')).map(firstSentence).join(' · '))} | ${cell(bullets(section(p.guide, "Doesn't suit")).map(firstSentence).join(' · '))} |`)
  put(`${S}/references/choosing.md`, choosing.join('\n') + '\n')

  const js = `// ${note(from)}\n`
  put(`${S}/emile-shaders.js`, js + template('emile-shaders', 'emile-shaders.js'))
  put(`${S}/pictures.js`, `// ${note('scripts/pictures.js')}\n` + fs.readFileSync(path.join(root, 'scripts', 'pictures.js'), 'utf8'))
  const catalog = [...filters, ...transitions].map(p => ({ pack: p.pack, glsl: p.glsl, passes: p.passes, guide: p.guide, folder: folderOf(p) }))
  put(`${S}/catalog.js`, `${js}// Every pack.json, shader.glsl (and pass shaders) and SKILL.md of this folder, for a page opened from file:// (which can't fetch them).\n;(function (root) {\n  (root.EmileShaders ??= {}).catalog = ${JSON.stringify(catalog, null, 1).replace(/\n/g, '\n  ')}\n})(typeof globalThis !== 'undefined' ? globalThis : this)\n`)
  put(`${S}/example.html`, template('emile-shaders', 'example.html').replace(/^<!doctype html>\n/i, m => `${m}<!-- ${note(from)} -->\n`))
  for (const p of [...filters, ...transitions]) {
    for (const f of fs.readdirSync(p.dir).filter(f => !f.startsWith('.')).sort()) put(`${S}/${folderOf(p)}/${f}`, fs.readFileSync(path.join(p.dir, f)))
  }

  // ---------------------------------------------------------------- choosing-filters
  const C = 'skills/choosing-filters'
  const cmd = `<!-- ${note('the filters\' guides (emile/<name>/SKILL.md) and scripts/skills/choosing-filters/')} -->`
  const table = []
  for (const g of ORDER) {
    const group = filters.filter(p => p.pack.category === g)
    if (!group.length) continue
    table.push(`## ${GROUP[g]}`, '', '| Filter | Role | Moments it is for | How long | Fails on |', '|---|---|---|---|---|')
    for (const p of group) {
      const moments = bullets(section(p.guide, 'When to use')).filter(b => !/^Words that call for it/i.test(b)).map(momentOf)
      table.push(`| \`${p.pack.id}\` ${p.pack.title.en} | ${cell(section(p.guide, 'Role'))} | ${cell(moments.join(' · '))} | ${cell(section(p.guide, 'How long'))} | ${cell(bullets(section(p.guide, "Doesn't suit")).map(firstSentence).join(' · '))} |`)
    }
    table.push('')
  }
  const words = filters.map(p => `- \`${p.pack.id}\`: ${wordsOf(p.guide)}`).join('\n')
  put(`${C}/SKILL.md`, fill(template('choosing-filters', 'SKILL.md'), { generated: cmd, table: table.join('\n').trim(), words }))
  return out
}
